# -*- coding: utf-8 -*-
"""add_guide_links_to_hubs.py — One-off: inject a 'Free Guides' section into
each of the 9 category hub pages, linking to that category's zero-affiliate
informational guides generated by gen_info_pages.py. Completes the
hub-and-spoke internal linking the 50/20/20/10 content mix calls for
(guides <-> hub <-> reviews already exists the other direction)."""
import json
from pathlib import Path

DOCS_DIR = Path("docs")
SITE_URL = "https://trendvortex.tech"

# Re-derive hub_slug -> [(slug, title), ...] straight from the manifest +
# the same mapping gen_info_pages.py uses, without re-importing that module.
import importlib.util
spec = importlib.util.spec_from_file_location("gen_info_pages", "gen_info_pages.py")
gip = importlib.util.module_from_spec(spec)
spec.loader.exec_module(gip)

manifest = json.loads(Path("info_content_manifest.json").read_text(encoding="utf-8"))
by_hub: dict[str, list] = {}
for item in manifest:
    slug = item["slug"]
    cat_name, hub_slug = gip.TOPIC_CATEGORY[slug]
    by_hub.setdefault(hub_slug, []).append((slug, item["title"]))

updated = 0
for hub_slug, guides in by_hub.items():
    page_path = DOCS_DIR / hub_slug / "index.html"
    if not page_path.exists():
        print(f"  SKIP {hub_slug} — page not found")
        continue
    html = page_path.read_text(encoding="utf-8", errors="replace")
    if "guides-wrap" in html:
        print(f"  SKIP {hub_slug} — guide links already present")
        continue

    cards = "".join(
        f'<a href="{SITE_URL}/{slug}/" class="guide-card">📘 {title}</a>'
        for slug, title in guides
    )
    injection = f"""
<style>
.guides-wrap{{max-width:1100px;margin:0 auto;padding:0 20px 32px}}
.guides-h{{font-size:1.05rem;font-weight:900;margin-bottom:14px}}
.guides-grid{{display:flex;flex-wrap:wrap;gap:10px}}
.guide-card{{background:var(--card);border:1px solid var(--border);border-radius:10px;padding:12px 16px;font-size:.85rem;font-weight:600;color:var(--text);text-decoration:none;flex:1 1 260px}}
.guide-card:hover{{border-color:var(--cta)}}
</style>
<div class="guides-wrap">
  <div class="guides-h">Free Guides — No Product Links</div>
  <div class="guides-grid">{cards}</div>
</div>"""

    new_html = html.replace("</body>", f"{injection}\n</body>")
    page_path.write_text(new_html, encoding="utf-8")
    print(f"  OK  {hub_slug} — linked {len(guides)} guides")
    updated += 1

print(f"\n  {updated} hub pages updated with guide links")
